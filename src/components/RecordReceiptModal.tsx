import { ExternalLink, X, CreditCard, ShieldCheck } from "lucide-react";

const CLIENT_LEDGER_URL = "https://brandex-client-ledger.vercel.app";

interface RecordReceiptModalProps {
  isOpen: boolean;
  onClose: () => void;
  trademarkId: string;
  caseTitle: string;
  tmNumber?: string | null;
  clientCode?: string | null;
  initialStage?: "S1" | "S2" | "S3" | "S4";
  onReceiptRecorded?: (receipt: any) => void;
}

/**
 * Client receipt entry is intentionally handed off to the separate authoritative
 * Brandex Client Ledger. This CMS screen must never create a competing receipt.
 */
export function RecordReceiptModal({ isOpen, onClose, tmNumber, clientCode }: RecordReceiptModalProps) {
  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-black/60 p-4">
      <section role="dialog" aria-modal="true" aria-labelledby="ledger-handoff-title" className="w-full max-w-lg border-2 border-[#0C0C0C] bg-[#FAF6EE] p-6 shadow-[6px_6px_0_#0C0C0C]">
        <header className="mb-4 flex items-center justify-between border-b-2 border-[#0C0C0C] pb-3">
          <div className="flex items-center gap-2 font-mono text-sm font-bold uppercase">
            <CreditCard className="h-5 w-5 text-[#6C1C1F]" />
            Client Ledger
          </div>
          <button type="button" onClick={onClose} aria-label="Close" className="border border-[#0C0C0C] bg-white p-1">
            <X className="h-4 w-4" />
          </button>
        </header>
        <div className="space-y-3 font-mono text-sm text-[#0C0C0C]">
          <h2 id="ledger-handoff-title" className="text-lg font-bold uppercase">Record payment in Brandex Client Ledger</h2>
          <p>The separate Brandex Client Ledger is the authoritative financial record. This CMS screen cannot create receipts or change client balances.</p>
          <div className="border border-stone-400 bg-white p-3 text-xs">
            <p><strong>TM number:</strong> {tmNumber || "Not assigned — search by case/client in Ledger"}</p>
            <p><strong>Client code:</strong> {clientCode || "Not available"}</p>
            <p className="mt-2 flex items-center gap-2 text-[#0A6B52]"><ShieldCheck className="h-4 w-4 shrink-0" /> Official receipt numbers are generated by the Ledger system.</p>
          </div>
          <div className="flex flex-wrap justify-end gap-2 border-t border-stone-300 pt-4">
            <button type="button" onClick={onClose} className="border-2 border-[#0C0C0C] bg-white px-4 py-2 text-xs font-bold uppercase">Cancel</button>
            <a href={CLIENT_LEDGER_URL} target="_blank" rel="noopener noreferrer" className="inline-flex items-center gap-2 border-2 border-[#0C0C0C] bg-[#0A6B52] px-4 py-2 text-xs font-bold uppercase text-white">
              Open Client Ledger <ExternalLink className="h-4 w-4" />
            </a>
          </div>
        </div>
      </section>
    </div>
  );
}
